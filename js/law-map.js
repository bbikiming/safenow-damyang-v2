    function esc(s) {
        return String(s == null ? '' : s)
            .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
    }

    /* 현재 페이지의 실효 id — menu.html 쿼리까지 반영 */
    function pageId() {
        const raw = document.body.getAttribute('data-dy-page') || 'index';
        if (!/\/menu\.html$/.test(location.pathname)) return raw;
        const p = new URLSearchParams(location.search);
        const m = p.get('m');
        if (m === 'opinion') return OPINION_SUB[p.get('sub')] || 'opn-voice';
        return MENU_ALIAS[m] || raw;
    }

    function article(key) { return ARTICLES[key] || null; }
    function law(lawKey) { return LAWS[lawKey] || null; }

    /* 근거 조문 목록 — [{key, ...article, lawMeta}] */
    function forPage(id) {
        const keys = MAP[id || pageId()] || [];
        return keys.map(k => {
            const a = ARTICLES[k];
            if (!a) return null;
            return Object.assign({ key: k, lawMeta: LAWS[a.law] || {} }, a);
        }).filter(Boolean);
    }

    /* 짧은 표기 — '중처법 시행령 §4 1호' · '산안법 시행규칙 별표4' */
    function shortRef(key) {
        const a = ARTICLES[key];
        if (!a) return key;
        const L = LAWS[a.law] || {};
        const jo = String(a.jo).replace(/^제/, '§').replace(/조$/, '');
        const cl = a.clause ? ' ' + a.clause.replace(/^제/, '') : '';
        return (L.short || L.name || '') + ' ' + jo + cl;
    }

    /* 법제처 원문 링크 — 조문 단위 딥링크.
     * 행정규칙(rule)은 /행정규칙/ 경로, 별표는 법령 단위 링크만 건다. */
    function lawUrl(key) {
        const a = ARTICLES[key];
        if (!a) return 'https://www.law.go.kr';
        const L = LAWS[a.law] || {};
        const name = (L.name || '').replace(/\s+/g, '');
        const base = L.rule ? '행정규칙' : '법령';
        if (L.rule || a.kind === '별표') {
            return 'https://www.law.go.kr/' + base + '/' + encodeURIComponent(name);
        }
        return 'https://www.law.go.kr/' + base + '/' + encodeURIComponent(name) + '/' + encodeURIComponent(a.jo);
    }

