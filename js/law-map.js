    /* 칩 토글 — 같은 묶음(.law-basis-row 한 줄 / .law-basis-inline 한 칩) 안에서만
     * 상태를 다룬다. 표 안 여러 행이 서로의 패널을 닫지 않는다. */
    function toggle(btn, key, panelId) {
        const host0 = btn.closest('.law-basis-inline, .law-basis-row');
        if (!host0) return;
        const host = host0.querySelector('.law-basis-panels');
        const open = btn.getAttribute('aria-expanded') === 'true';

        host0.querySelectorAll('.law-basis-chip').forEach(b => b.setAttribute('aria-expanded', 'false'));
        if (host) host.innerHTML = '';

        if (!open) {
            btn.setAttribute('aria-expanded', 'true');
            if (host) host.innerHTML = panelHtml(key, panelId);
        }
    }

    /* 페이지 제목 아래 근거 줄 주입 — layout.js mount() 에서 호출 */
    function inject(mainEl, id) {
        if (!mainEl || mainEl.querySelector('.law-basis-row')) return;
        const html = chipsHtml(id);
        if (!html) return;

        const title = mainEl.querySelector('.dy-page-title');
        if (!title) return;
        /* 부제가 있으면 부제 뒤에 붙인다 */
        let anchor = title;
        const next = title.nextElementSibling;
        if (next && next.classList.contains('dy-page-subtitle')) anchor = next;

        const wrap = document.createElement('div');
        wrap.innerHTML = html;
        anchor.insertAdjacentElement('afterend', wrap.firstElementChild);
    }

