        const out = [];
        a.text.split('\n').forEach(line => {
            const m = /^(\d+)\.\s+(.+)$/.exec(line);   /* 들여쓴 목(　가.)은 매칭되지 않는다 */
            if (m && +m[1] >= 1 && +m[1] <= 39) out.push({ no: +m[1], name: m[2] });
        });
        /* '1. 근로자 안전보건교육(제26조제1항 관련)' 머리글이 no=1 로 잡히지 않도록,
         * 같은 번호가 두 번 나오면 뒤엣것(개별내용)을 채택한다. */
        const byNo = {};
        out.forEach(x => { byNo[x.no] = x; });
        return Object.keys(byNo).map(Number).sort((x, y) => x - y).map(n => byNo[n]);
