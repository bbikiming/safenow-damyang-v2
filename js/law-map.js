    function resolveBasis(basis) {
        if (!basis) return null;
        if (ARTICLES[basis]) return basis;
        const s = String(basis).trim();
        if (BASIS_ALIAS[s]) return BASIS_ALIAS[s];
        /* '산안법 §29 · 반기' 처럼 주기 접미사가 붙은 표기 — 앞머리로 재시도.
         * (주기는 근거 조문이 아니라 운영 정보라 조문 해석에서 떼어낸다.) */
        const head = s.split('·')[0].trim();
        return (head !== s && BASIS_ALIAS[head]) || null;
    }

