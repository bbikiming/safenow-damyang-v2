if __name__ == '__main__':
    D = json.load(open('/tmp/gnbrows.json', encoding='utf-8'))
    SFRNAME = D['SFR']
    miss = [r['page'] for r in D['rows'] if r['page'] not in VERIFIED]
    extra = [k for k in VERIFIED if k not in {r['page'] for r in D['rows']}]
    print('메뉴 %d개 · 판정 %d개' % (len(D['rows']), len(VERIFIED)))
    print('판정 누락:', miss or '없음')
    print('메뉴에 없는 판정 키:', extra or '없음')
    bad = [s for v in VERIFIED.values() for s in v[0] if s not in SFRNAME]
    print('존재하지 않는 요구사항 참조:', bad or '없음')

    print('\n=== 코드 주석과 달라지는 화면 ===')
    n = 0
    for r in D['rows']:
        old = set(r['sfr']); new = set(VERIFIED[r['page']][0])
        if old != new:
            n += 1
            print('  %-14s %-22s  코드[%s]  →  검증[%s]' % (
                r['page'], r['group'] + '>' + r['label'],
                ','.join(sorted(old)) or '—', ','.join(sorted(new)) or '—'))
    print('  총 %d개 화면' % n)
    json.dump({k: {'sfr': v[0], 'why': v[1]} for k, v in VERIFIED.items()},
              open('/tmp/sfr_verified.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
